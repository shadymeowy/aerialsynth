#[derive(Args)]
pub struct ViewArgs {
    #[command(flatten)]
    pub common: Common,
    #[command(flatten)]
    pub view: viewer::ViewOptions,
}

/// The world on a globe (map) and through a camera (the dataset renderer), flown live.
pub fn view(a: ViewArgs) -> Result<()> {
    let s = setup(&a.common)?;
    let gen = Generator::new(s.world.clone());
    let store = pipeline::open_or_create_store(&s, &gen)?;
    viewer::run(s, Arc::new(store), Arc::new(gen), a.view)
}

#[derive(Args)]
pub struct ConfigArgs {
    #[command(flatten)]
    pub common: Common,
    /// Every setting with its default instead of the short template (with -c the whole resolved
    /// scenario is printed anyway). Sections that are off by default (a camera's events, stars)
    /// show their settings only when turned on, e.g. `events: {}` in a scenario given with -c.
    #[arg(long)]
    pub all: bool,
}

/// The main settings, commented: a starting point for a scenario.
pub const TEMPLATE: &str = include_str!("template.yaml");

pub fn config(a: ConfigArgs) -> Result<()> {
    if a.common.config.is_none() && a.common.seed.is_none() && !a.all {
        print!("{TEMPLATE}");
        return Ok(());
    }
    let s = setup(&a.common)?;
    print!("{}", s.to_yaml());
    Ok(())
}

#[derive(Args)]
pub struct InfoArgs {
    pub file: PathBuf,
}

pub fn info(a: InfoArgs) -> Result<()> {
    if let Ok(st) = TileStore::open(&a.file) {
        let m = st.meta();
        println!(
            "tile store {} (seed {}, generator version {}{}, ellipsoid a={} b={:.6})",
            a.file.display(),
            m.seed,
            m.generator_version,
            if m.generator_version == terragen::GENERATOR_VERSION { "" } else { " — not this binary's" },
            m.ellipsoid_a,
            m.ellipsoid_b
        );
        println!("layers: {:?}", m.layers.iter().map(|l| l.name()).collect::<Vec<_>>());
        for z in st.zooms() {
            let t = st.tiles_at(z);
            let (mut lo, mut hi) = (f32::MAX, f32::MIN);
            for id in &t {
                if let Some((a, b)) = st.elev_range(*id) {
                    lo = lo.min(a);
                    hi = hi.max(b);
                }
            }
            println!("  z{z:2}: {:6} tiles  elevation {lo:.0} .. {hi:.0} m", t.len());
        }
        return Ok(());
    }
    let f = h5::File::open(&a.file)?;
    use h5::Attrs;
    println!("{} (format {:?})", a.file.display(), f.attr_str("format").unwrap_or_default());
    fn walk(g: &h5::Group, prefix: &str, depth: usize) -> Result<()> {
        for name in g.member_names()? {
            let path = format!("{prefix}/{name}");
            if let Ok(ds) = g.dataset(&name) {
                println!("{}{path}: {:?}", "  ".repeat(depth), ds.shape()?);
            } else {
                println!("{}{path}/", "  ".repeat(depth));
                walk(&g.group(&name)?, &path, depth + 1)?;
            }
        }
        Ok(())
    }
    walk(&f, "", 1)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The template parses, and every value it shows is the default.
    #[test]
    fn template_shows_the_defaults() {
        let t: Scenario = serde_yaml::from_str(TEMPLATE).expect("template parses");
        t.validate().unwrap();
        let d = Scenario::default();
        assert_eq!(serde_yaml::to_string(&t.world).unwrap(), serde_yaml::to_string(&d.world).unwrap());
        assert_eq!(serde_yaml::to_string(&t.tiles).unwrap(), serde_yaml::to_string(&d.tiles).unwrap());
        assert_eq!(serde_yaml::to_string(&t.trajectory).unwrap(), serde_yaml::to_string(&d.trajectory).unwrap());
        assert_eq!(serde_yaml::to_string(&t.render).unwrap(), serde_yaml::to_string(&d.render).unwrap());
        assert_eq!(serde_yaml::to_string(&t.output).unwrap(), serde_yaml::to_string(&d.output).unwrap());
    }
}
